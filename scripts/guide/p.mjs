// gruppo P: seme e Rigenera di un set a caso, scelta dei componenti da esportare con prima e dopo
import { launch, shotEl } from './lib.mjs'
const lang = process.argv[2]
const it = lang === 'it'
const { app, win, T } = await launch({ lang, h: 1000 })
if (process.env.DEBUG)
  win.on('console', (m) => m.type() === 'error' && console.log('CONSOLE', m.text().slice(0, 400)))
if (process.env.DEBUG) win.on('pageerror', (e) => console.log('PAGEERROR', e.message))
const dialog = () => win.locator('[role="dialog"]').last()
await win
  .locator('.sidebar')
  .getByText(it ? 'Mercato' : 'Market', { exact: true })
  .click()
await win.waitForTimeout(800)
// un backup prima delle modifiche
await win.getByRole('button', { name: `${T['app.projectMenu']} ▾` }).click()
await win.getByRole('menuitem', { name: T['app.backup'] }).click()
await win.waitForTimeout(1200)
await dialog().getByRole('button', { name: T['backup.create'] }).click()
await win.waitForTimeout(2000)
await dialog().getByRole('button', { name: T['dialog.close'], exact: true }).last().click()
await win.waitForTimeout(500)
// risorse a caso nelle carte del mercato
await win.getByRole('button', { name: `${T['set.tools']} ▾` }).click()
await win.getByRole('menuitem', { name: T['set.generate'] }).click()
await win.waitForTimeout(800)
await dialog().getByText(T['generate.random'], { exact: true }).click()
const set = dialog().locator('.generate-set').first()
await set.locator('textarea').fill(it ? 'legno\npietra\ngrano' : 'wood\nstone\nwheat')
await dialog().getByText(T['generate.update'], { exact: true }).click()
await win.waitForTimeout(500)
await dialog().locator('.dialog-buttons button.primary').click()
await win.waitForTimeout(1200)
const rows = () => win.locator('.card-label').allInnerTexts()
const before = (await rows()).join('|')
await shotEl(win, `${lang}/rigenera`, win.locator('.set-actions').first(), 12)
await win.getByRole('button', { name: `🎲 ${T['set.regenerate']}` }).click()
await win.waitForTimeout(1000)
const after = (await rows()).join('|')
console.log('regenerate changed rows:', before !== after)
const seed = await win.locator('.seed-field input').inputValue()
await win.locator('.seed-field input').fill('7')
await win.locator('.seed-field input').press('Enter')
await win.waitForTimeout(800)
const seven = (await rows()).join('|')
await win.getByRole('button', { name: `🎲 ${T['set.regenerate']}` }).click()
await win.waitForTimeout(800)
await win.locator('.seed-field input').fill('7')
await win.locator('.seed-field input').press('Enter')
await win.waitForTimeout(800)
console.log('seed', seed, 'same seed same rows:', seven === (await rows()).join('|'))
// esportazione: solo i componenti cambiati dal backup, con il prima e il dopo
await win.getByRole('button', { name: T['app.export'], exact: true }).click()
await win.waitForTimeout(1500)
await dialog().getByText(T['export.goal.home'], { exact: true }).first().click()
await win.waitForTimeout(1000)
await dialog().getByRole('button', { name: T['pick.button'] }).click()
await win.waitForTimeout(1500)
await dialog().getByRole('button', { name: T['pick.selectChanged'] }).click()
await win.waitForTimeout(3000)
await shotEl(win, `${lang}/scegli-componenti`, dialog(), 24)
await app.close()
