// gruppo O: Informazioni progetto (nome, autore, versione, copertina, cartella)
import { launch, shotEl, OUT } from './lib.mjs'
import { mkdirSync, rmSync } from 'node:fs'
const lang = process.argv[2]
mkdirSync(`${OUT}/${lang}`, { recursive: true })
rmSync('/tmp/stella-guide/ud-' + lang, { recursive: true, force: true })
const { app, win, T } = await launch({ lang })
await win.getByRole('button', { name: `${T['app.projectMenu']} ▾` }).click()
await win.getByRole('menuitem', { name: T['projectInfo.menu'] }).click()
await win.waitForTimeout(600)
const dlg = win.locator('[role="dialog"]').first()
const inputs = dlg.locator('input')
await inputs.nth(1).fill('Luca Di Gialleonardo')
await inputs.nth(2).fill('0.3')
// la copertina: un componente scelto dalla finestra delle carte
await dlg.getByRole('button', { name: T['projectInfo.coverComponent'] }).click()
await win.waitForTimeout(800)
const picker = win.locator('[role="dialog"]').last()
await picker.locator('.insert-card-grid > *').nth(2).click()
await win.waitForTimeout(500)
await shotEl(win, `${lang}/copertina-componente`, picker, 24)
await picker.getByRole('button', { name: T['documents.pick'], exact: true }).click()
await win.waitForTimeout(800)
await win.mouse.move(5, 5)
await win.waitForTimeout(300)
await shotEl(win, `${lang}/informazioni-progetto`, dlg, 24)
// e la finestra delle immagini
await dlg.getByRole('button', { name: T['projectInfo.coverImage'] }).click()
await win.waitForTimeout(1000)
await win.screenshot({ path: `${OUT}/${lang}/check-copertina-immagine.png` })
await app.close()
